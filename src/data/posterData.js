/**
 * Цитаты к трекам: [начало названия трека, цитата]. Показываются в окошке трека
 * и под названием книги, пока трек звучит. Кавычки-ёлочки ставит вёрстка.
 * Опечатка в названии не ломает постер, а выводит предупреждение в консоль.
 */
function attachQuotes(tracks, rows) {
  for (const [title, text] of rows) {
    const found = tracks.find((item) => item.title.startsWith(title))
    if (found) found.quote = text
    else console.warn(`Трек для цитаты не найден: «${title}»`)
  }
}

